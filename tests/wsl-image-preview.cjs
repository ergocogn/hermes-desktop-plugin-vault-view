// Synthetic integration fixture; no vault notes or attachments are read.
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const assert = require('node:assert/strict')
const { execFileSync } = require('node:child_process')
const fixtureId = process.pid + '-' + Date.now()
const input = path.join(__dirname, '.synthetic-preview-' + fixtureId + '.png')
const output = path.join(__dirname, '.synthetic-preview-' + fixtureId + '.webp')
const posix = value => '/mnt/' + value[0].toLowerCase() + value.slice(2).replace(/\\/g, '/')
const quote = value => "'" + value.replace(/'/g, "'\\''") + "'"
const shell = command => execFileSync('wsl.exe', ['-d', process.env.VAULT_TEST_DISTRO || 'Ubuntu', '--', 'sh', '-c', command], { encoding: 'utf8', windowsHide: true })
const sandbox = {
  console, TextEncoder, TextDecoder, Uint8Array, btoa, atob,
  host: { request: async (_, { command }) => ({ result: { code: 0, stdout: shell(command).slice(-4000) } }) },
}
const source = fs.readFileSync(path.join(__dirname, '..', 'plugin.js'), 'utf8').replace(/^import .*$/gm, '').replace('export default {', 'globalThis.plugin = {')
vm.runInNewContext(source + '\nglobalThis.preview = readImageThumbnailDataUrl', sandbox)
;(async () => {
  try {
    assert.equal(fs.existsSync(input), false)
    assert.equal(fs.existsSync(output), false)
    shell('ffmpeg -hide_banner -loglevel error -f lavfi -i testsrc2=size=2000x1400 -frames:v 1 ' + quote(posix(input)))
    const urls = await Promise.all([sandbox.preview(posix(input)), sandbox.preview(posix(input))])
    assert.ok(urls.every(url => url.startsWith('data:image/webp;base64,')), 'concurrent real thumbnails must all succeed')
    const url = urls[0]
    assert.ok(url.startsWith('data:image/webp;base64,'), 'thumbnail must be generated by the real pipeline')
    const bytes = Buffer.from(url.split(',')[1], 'base64')
    fs.writeFileSync(output, bytes, { flag: 'wx' })
    const dimensions = JSON.parse(shell('ffprobe -v error -select_streams v:0 -show_entries stream=width,height -of json ' + quote(posix(output))))
    assert.equal(dimensions.streams[0].width, 1400)
    assert.ok(dimensions.streams[0].height < 1400)
    assert.ok(bytes.length < fs.statSync(input).size)
    console.log('Vault View real WSL preview: OK (real ffmpeg, WebP decoding, reduced dimensions and size)')
  } finally {
    for (const file of [input, output]) if (fs.existsSync(file)) fs.unlinkSync(file)
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
